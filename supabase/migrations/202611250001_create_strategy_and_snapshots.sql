-- 1. 매일 자동 적재되는 일자별 객실 가격·최소박수·재고 스냅샷 (원인 데이터)
CREATE TABLE IF NOT EXISTS public.daily_inventory_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date DATE NOT NULL,
    target_date DATE NOT NULL,
    lead_days INTEGER NOT NULL,
    property_id INTEGER NOT NULL,
    room_id INTEGER NOT NULL,
    price INTEGER NOT NULL DEFAULT 0,
    min_stay INTEGER NOT NULL DEFAULT 1,
    num_avail INTEGER NOT NULL DEFAULT 0,
    override_type TEXT NOT NULL DEFAULT 'none',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (snapshot_date, room_id, target_date)
);

CREATE INDEX IF NOT EXISTS idx_daily_inv_snapshots_date
    ON public.daily_inventory_snapshots (snapshot_date DESC, target_date ASC);

CREATE INDEX IF NOT EXISTS idx_daily_inv_snapshots_room
    ON public.daily_inventory_snapshots (room_id, target_date, snapshot_date DESC);

-- 2. PriceLabs / Beds24 / OTA 프로모션·광고 설정 변경 이력 (Before/After 성적표용)
CREATE TABLE IF NOT EXISTS public.strategy_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_date DATE NOT NULL,
    end_date DATE,
    source_type TEXT NOT NULL DEFAULT 'pricelabs', -- 'pricelabs', 'beds24', 'ota_promo', 'ota_ads', 'operation'
    property_name TEXT NOT NULL DEFAULT 'all',     -- 'all', 'WAVE', 'YEONNAM', 'Green', 'Horang'
    unit_key TEXT,
    channel_id INTEGER,
    title TEXT NOT NULL,
    rule_detail TEXT NOT NULL DEFAULT '',
    compare_days INTEGER NOT NULL DEFAULT 14 CHECK (compare_days IN (7, 14, 28, 30)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_strategy_events_date
    ON public.strategy_events (event_date DESC);
